//! Generate the client contract from the same types used by the reader and writer.
use ox_desk_core::host_protocol::{Client, Server};
use serde_json::{Value, json};
use std::{collections::BTreeMap, env, fs, io, path::Path};

fn typescript(schema: &Value) -> String {
    if let Some(name) = schema["$ref"].as_str() {
        return name.rsplit('/').next().unwrap().into();
    }
    if let Some(value) = schema.get("const") {
        return value.to_string();
    }
    if let Some(values) = schema["enum"].as_array() {
        return values
            .iter()
            .map(Value::to_string)
            .collect::<Vec<_>>()
            .join(" | ");
    }
    for variant in ["oneOf", "anyOf", "allOf"] {
        if let Some(values) = schema[variant].as_array() {
            return format!(
                "({})",
                values
                    .iter()
                    .map(typescript)
                    .collect::<Vec<_>>()
                    .join(if variant == "allOf" { " & " } else { " | " })
            );
        }
    }
    if let Some(values) = schema["type"].as_array() {
        return values
            .iter()
            .map(|t| {
                let mut s = schema.clone();
                s["type"] = t.clone();
                typescript(&s)
            })
            .collect::<Vec<_>>()
            .join(" | ");
    }
    match schema["type"].as_str() {
        Some("boolean") => "boolean".into(),
        Some("number" | "integer") => "number".into(),
        Some("string") => "string".into(),
        Some("null") => "null".into(),
        Some("array") => {
            if let Some(items) = schema["prefixItems"].as_array() {
                format!(
                    "[{}]",
                    items.iter().map(typescript).collect::<Vec<_>>().join(", ")
                )
            } else {
                format!("Array<{}>", typescript(&schema["items"]))
            }
        }
        Some("object") => {
            let required = schema["required"].as_array();
            if let Some(fields) = schema["properties"].as_object() {
                format!(
                    "{{ {} }}",
                    fields
                        .iter()
                        .map(|(k, v)| {
                            let optional = if required
                                .is_some_and(|r| r.iter().any(|x| x.as_str() == Some(k)))
                            {
                                ""
                            } else {
                                "?"
                            };
                            format!("{k}{optional}: {}", typescript(v))
                        })
                        .collect::<Vec<_>>()
                        .join("; ")
                )
            } else {
                format!(
                    "Record<string, {}>",
                    typescript(&schema["additionalProperties"])
                )
            }
        }
        _ => "unknown".into(),
    }
}

fn main() -> io::Result<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("generated");
    let mut definitions = BTreeMap::<String, Value>::new();
    for (name, schema) in [
        ("Client", schemars::schema_for!(Client)),
        ("Server", schemars::schema_for!(Server)),
    ] {
        let mut value = serde_json::to_value(schema)?;
        if let Some(Value::Object(defs)) = value.as_object_mut().unwrap().remove("$defs") {
            for (key, v) in defs {
                if let Some(previous) = definitions.insert(key, v.clone()) {
                    assert_eq!(previous, v);
                }
            }
        }
        value.as_object_mut().unwrap().remove("$schema");
        definitions.insert(name.into(), value);
    }
    let decl = definitions
        .iter()
        .map(|(k, v)| format!("export type {k} = {};\n", typescript(v)))
        .collect::<String>();
    let schema = json!({"$schema":"https://json-schema.org/draft/2020-12/schema","$defs":definitions,"oneOf":[{"$ref":"#/$defs/Client"},{"$ref":"#/$defs/Server"}]});
    let check = env::args().skip(1).any(|a| a == "--check");
    for (file, body) in [
        (
            "host-v1.schema.json",
            serde_json::to_string_pretty(&schema)? + "\n",
        ),
        (
            "host-v1.d.ts",
            String::from("// Generated by ox-host-protocol.\n") + &decl,
        ),
    ] {
        let path = root.join(file);
        if check {
            if fs::read_to_string(&path)? != body {
                return Err(io::Error::other(format!("Stale {file}")));
            }
        } else {
            fs::write(path, body)?;
        }
    }
    Ok(())
}
